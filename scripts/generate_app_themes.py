#!/usr/bin/env python3
"""Build the desktop app's built-in themes from a folder of VS Code themes.

Usage:
    python3 scripts/generate_app_themes.py [SOURCE_DIR] [OUTPUT_FILE]

The app does not read VS Code files at runtime. This script distils each
`colors` workbench block into the eight tokens SOLEXA's UI uses, and writes
TypeScript that ships in the bundle. Run it again only when the source
themes change.

Token mapping (first key that exists wins):
    bg      editor.background
    panel   sideBar.background, editorWidget.background
    line    panel.border, editorGroup.border, contrastBorder
    ink     editor.foreground, foreground
    muted   descriptionForeground, editorLineNumber.foreground
    accent  activityBarBadge.background, button.background, textLink.foreground
    ok      terminal.ansiGreen, charts.green, gitDecoration.addedResourceForeground
    danger  errorForeground, terminal.ansiRed
"""

import json
import re
import sys
from pathlib import Path

DEFAULT_SRC = Path(r"D:\vsc\theme\mh3nj-themes")
OUT = Path(__file__).resolve().parent.parent / "apps" / "desktop" / "frontend" / "src" / "themes" / "defaults.ts"

FALLBACK = {
    "bg": "#12151b",
    "panel": "#1a1f28",
    "line": "#2a3140",
    "ink": "#e7e9ee",
    "muted": "#8a93a6",
    "accent": "#e3a857",
    "ok": "#4fd1c5",
    "danger": "#e1616b",
}

MAP = {
    "bg": ("editor.background",),
    "panel": ("sideBar.background", "editorWidget.background"),
    "line": ("panel.border", "editorGroup.border", "contrastBorder"),
    "ink": ("editor.foreground", "foreground"),
    "muted": ("descriptionForeground", "editorLineNumber.foreground"),
    "accent": ("activityBarBadge.background", "button.background", "textLink.foreground"),
    "ok": ("terminal.ansiGreen", "charts.green", "gitDecoration.addedResourceForeground"),
    "danger": ("errorForeground", "terminal.ansiRed"),
}

HEX = re.compile(r"^#([0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")


def parse(value):
    """Return (#rrggbb, alpha 0..1) for a VS Code color, else None."""
    if not isinstance(value, str) or not HEX.match(value):
        return None
    digits = value[1:]
    if len(digits) in (3, 4):
        digits = "".join(ch * 2 for ch in digits)
    rgb = "#" + digits[:6].lower()
    alpha = int(digits[6:8], 16) / 255 if len(digits) == 8 else 1.0
    return rgb, alpha


def blend(rgb, alpha, background):
    """Composite a possibly translucent color over the theme background."""
    if alpha >= 0.999:
        return rgb
    fg = [int(rgb[i : i + 2], 16) for i in (1, 3, 5)]
    bg = [int(background[i : i + 2], 16) for i in (1, 3, 5)]
    mixed = [round(f * alpha + b * (1 - alpha)) for f, b in zip(fg, bg)]
    return "#" + "".join(f"{c:02x}" for c in mixed)


def pick(colors, keys, background=None):
    for key in keys:
        parsed = parse(colors.get(key))
        if parsed:
            rgb, alpha = parsed
            return blend(rgb, alpha, background or FALLBACK["bg"])
    return None


def slug_to_name(slug):
    parts = slug.split("-")
    return " ".join(p.capitalize() for p in parts)


def build_theme(path, labels):
    data = json.loads(path.read_text(encoding="utf-8"))
    colors = data.get("colors") or {}
    background = pick(colors, MAP["bg"]) or FALLBACK["bg"]
    tokens = {"bg": background}
    for token, keys in MAP.items():
        if token == "bg":
            continue
        tokens[token] = pick(colors, keys, background) or FALLBACK[token]
    theme_id = path.stem
    label = labels.get(path.name) or slug_to_name(theme_id)
    kind = data.get("type") if data.get("type") in ("dark", "light") else (
        "light" if theme_id.endswith("-light") else "dark"
    )
    return {
        "id": theme_id,
        "name": label,
        "kind": kind,
        "builtin": True,
        **tokens,
    }


def read_labels(src):
    package = src / "package.json"
    labels = {}
    if not package.exists():
        return labels
    try:
        data = json.loads(package.read_text(encoding="utf-8"))
        for entry in data.get("contributes", {}).get("themes", []):
            path = entry.get("path", "").lstrip("./")
            label = entry.get("label")
            if path and label:
                labels[path] = label
    except (json.JSONDecodeError, OSError):
        pass
    return labels


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    if not src.is_dir():
        sys.exit(f"theme folder not found: {src}")

    labels = read_labels(src)
    paths = sorted(p for p in src.glob("*.json") if p.name != "package.json")
    themes = [build_theme(p, labels) for p in paths]
    themes.sort(key=lambda t: (t["kind"] != "dark", t["name"].lower()))

    lines = [
        "// Generated by scripts/generate_app_themes.py. Do not edit by hand.",
        "// Each entry is a distilled copy of a VS Code theme: eight UI tokens,",
        "// the family name, and whether it is a light or dark theme.",
        "",
        "export interface BuiltinTheme {",
        "  id: string;",
        "  name: string;",
        "  kind: \"dark\" | \"light\";",
        "  builtin: true;",
        "  bg: string;",
        "  panel: string;",
        "  line: string;",
        "  ink: string;",
        "  muted: string;",
        "  accent: string;",
        "  ok: string;",
        "  danger: string;",
        "}",
        "",
        "export const BUILTIN_THEMES: BuiltinTheme[] = [",
    ]
    for theme in themes:
        lines.append("  {")
        lines.append(f"    id: {json.dumps(theme['id'])},")
        lines.append(f"    name: {json.dumps(theme['name'])},")
        lines.append(f"    kind: {json.dumps(theme['kind'])},")
        lines.append("    builtin: true,")
        for token in ("bg", "panel", "line", "ink", "muted", "accent", "ok", "danger"):
            lines.append(f"    {token}: {json.dumps(theme[token])},")
        lines.append("  },")
    lines.append("];")
    lines.append("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {len(themes)} themes to {out}")


if __name__ == "__main__":
    main()
